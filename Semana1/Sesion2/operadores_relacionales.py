#Leer dos numeros y compararlos
number1 = int(input("Ingresa un #: "))
number2 = int(input("Ingresa otro #: "))

print(f"{number1} > {number2} = {number1 > number2}")
print(f"{number1} < {number2} = {number1 < number2}")
print(f"{number1} >= {number2} = {number1 >= number2}")
print(f"{number1} <= {number2} = {number1 <= number2}")
print(f"{number1} == {number2} = {number1 == number2}")
print(f"{number1} != {number2} = {number1 != number2}")